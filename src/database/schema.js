import {
  DEFAULT_TRACKING_DOMAINS,
  DEFAULT_WATCHED_COOKIES,
  DEFAULT_SETTINGS,
} from './defaults.js';

// The extension keeps all of its data in one IndexedDB database.
// The background worker and the popup each open their own connection to it and see the same records.
export const DATABASE_NAME = 'UTMDebugger';

// IndexedDB only creates or changes stores when this number goes up.
// After people have used the extension, changing a store or index means raising it and adding upgrade code.
export const DATABASE_VERSION = 1;

// The points in a page load where a cookie snapshot can be taken.
export const DOCUMENT_STAGES = ['start', 'end', 'idle'];

// Every store (similar to a table in SQL) and the record field used as its primary key.
export const STORE_KEYS = {
  trackingDomains: 'domain',
  requests: 'id',
  watchedCookies: 'name',
  cookieSnapshots: 'id',
  lastSeenValues: 'name',
  settings: 'key',
};

/**
 * Creates every store and index, then adds the default configuration.
 * The manager calls this when the browser creates the database for the first time.
 *
 * @param {IDBDatabase} database The new database. Stores can only be created at this point.
 * @returns {void}
 */
export function initializeSchema(database) {
  // Tracking domains: The analytics and advertising services the extension recognizes.
  // A domain also covers its subdomains, so `clarity.ms` matches `x.clarity.ms`.
  //   - `domain` Primary key, e.g. `clarity.ms`.
  //   - `providerName` Name shown to the user, e.g. 'Microsoft Clarity'.
  //   - `extractorName` Name of the function that reads this provider's requests.
  //   - `excludeIfContains` Text that marks a request as not worth recording, such as `script` for script downloads. Checked against the request's hostname and path, never its query string.
  //   - `captureEnabled` Whether the listener should record this domain's requests.
  const trackingDomains = database.createObjectStore('trackingDomains', {
    keyPath: STORE_KEYS.trackingDomains,
  });
  // An index lets IndexedDB find records by a field other than the primary key.
  trackingDomains.createIndex('providerName', 'providerName');
  trackingDomains.createIndex('extractorName', 'extractorName');
  // Requests: Network requests that a page sent to a tracking domain, saved by the listener together with what that provider's extractor found in them.
  //   - `id` Primary key. IndexedDB generates it because `autoIncrement` is on.
  //   - `requestId` Chrome's ID for the request (`details.requestId`).
  //   - `url` Full URL the request was sent to (`details.url`).
  //   - `method` HTTP method, such as 'GET' or 'POST' (`details.method`).
  //   - `timeStamp` When Chrome saw the request, in milliseconds (`details.timeStamp`).
  //   - `tabId` Tab that sent the request, or -1 when no tab did (`details.tabId`).
  //   - `hostname` Filled in from `url` by the database.
  //   - `pageURL` Page the user was on, or `null` when it is unknown.
  //   - `utmSource` utm_source value the extractor found, or `null`.
  //   - `utmMedium` utm_medium value the extractor found, or `null`.
  //   - Optional: `frameId`, `initiator`, and any other fields the extractor returns.
  const requests = database.createObjectStore('requests', {
    keyPath: STORE_KEYS.requests,
    autoIncrement: true,
  });
  const requestIndexes = [
    'requestId',
    'tabId',
    'hostname',
    'pageURL',
    'timeStamp',
    'utmSource',
    'utmMedium',
  ];
  for (const field of requestIndexes) {
    requests.createIndex(field, field);
  }
  // Watched cookies: The cookie names worth recording, such as utm_source.
  //   - `name` Primary key, the cookie's name.
  //   - `valueType` What the cookie holds, e.g. `source`, `email`, or `sessionId`.
  //   - `providerName` Service that sets the cookie, or 'Generic' when many services use it.
  const watchedCookies = database.createObjectStore('watchedCookies', {
    keyPath: STORE_KEYS.watchedCookies,
  });
  watchedCookies.createIndex('valueType', 'valueType');
  watchedCookies.createIndex('providerName', 'providerName');
  // Cookie snapshots: The value a watched cookie had at one point during a page load.
  //   - `id` Primary key, generated by IndexedDB.
  //   - `cookieName` Name of the watched cookie.
  //   - `value` The cookie's value. Cookie values are always strings.
  //   - `documentStage` One of `DOCUMENT_STAGES`.
  //   - `pageURL` Page the snapshot was taken on, or `null` when it is unknown.
  //   - `timeStamp` When the snapshot was taken, in milliseconds.
  //   - Optional: `domain`, `path` and any other cookie details worth keeping.
  const cookieSnapshots = database.createObjectStore('cookieSnapshots', {
    keyPath: STORE_KEYS.cookieSnapshots,
    autoIncrement: true,
  });
  const cookieSnapshotIndexes = ['cookieName', 'value', 'documentStage', 'pageURL', 'timeStamp'];
  for (const field of cookieSnapshotIndexes) {
    cookieSnapshots.createIndex(field, field);
  }
  // Last seen values where the most recent value of something compared from page to page, such as a provider session ID (one record per name).
  //   - `name` Primary key, chosen by the caller, e.g. 'GA4SessionID'.
  //   - `value` Any value IndexedDB can store.
  database.createObjectStore('lastSeenValues', {keyPath: STORE_KEYS.lastSeenValues});
  // Settings: User preferences. One record per setting.
  //   - `key` Primary key, e.g. `captureTrackingRequests`.
  //   - `value` Any value IndexedDB can store.
  const settings = database.createObjectStore('settings', {keyPath: STORE_KEYS.settings});
  // The defaults are added in the same transaction that creates the stores, so nobody can read the database before they exist.
  // This function never runs again for the same database, so anything the user edits or deletes stays that way.
  for (const trackingDomain of DEFAULT_TRACKING_DOMAINS) {
    trackingDomains.add(trackingDomain);
  }
  for (const watchedCookie of DEFAULT_WATCHED_COOKIES) {
    watchedCookies.add(watchedCookie);
  }
  for (const setting of DEFAULT_SETTINGS) {
    settings.add(setting);
  }
}
